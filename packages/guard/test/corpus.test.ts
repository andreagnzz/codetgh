const CASES = [...EN, ...FR];
const meta = (i: number) => ({
  id: `msg_${String(i).padStart(26, "0")}`,
  from: 'Léa "<x>"',
  agent: "agt_01",
  kind: "note",
  priority: "normal",
  authoredBy: "agent" as const,
  sentAt: new Date("2026-10-13T09:41:12Z"),
  flags: ["instruction-like"],
});

describe("injection corpus", () => {
  it("has at least 100 FR and EN texts", () => {
    expect(EN.length).toBeGreaterThanOrEqual(50);
    expect(FR.length).toBeGreaterThanOrEqual(50);
  });

  it.each(CASES.map(([text, flagged], i) => [i, text, flagged] as const))(
    "case %i stays inside one escaped envelope",
    (i, text, flagged) => {
      const out = renderPeerMessage(meta(i), null, text);
      expect(out).toMatch(/^<peer_message( [a-z_]+="[^"<>]*")+>\n[^<>]*\n<\/peer_message>$/);
      expect(out.match(/<peer_message /g)).toHaveLength(1);
      expect(out.match(/<\/peer_message>/g)).toHaveLength(1);
      expect(out).toMatch(/ trust="untrusted-peer">\n/);
      if (flagged) expect(textFlags(text)).toContain("instruction-like");
    },
  );
});
